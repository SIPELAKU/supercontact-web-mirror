// Builds app/dark-palette.css: dark mode for Tailwind's colour scales.
//
//   node scripts/dark-palette.mjs > app/dark-palette.css
//
// Values come from Tailwind's own theme (node_modules/tailwindcss/theme.css),
// written out in full because Tailwind only emits the colour variables a
// page uses. lib/utils/darkPalette.test.ts fails when the file is stale.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const PALETTE_COLORS = [
  "red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan",
  "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose",
];

/** How strong the 500 colour shows through the pale shades in dark mode. */
export const TINT_PERCENT = { 50: 12, 100: 20, 200: 32 };

const esc = (cls) => cls.replace(/:/g, "\\:");

export function buildDarkPaletteCss(themeCss) {
  const value = (color, shade) => {
    const m = themeCss.match(new RegExp(`--color-${color}-${shade}:\\s*([^;]+);`));
    if (!m) throw new Error(`Tailwind theme has no --color-${color}-${shade}`);
    return m[1].trim();
  };

  const vars = [];
  const rules = [];
  for (const c of PALETTE_COLORS) {
    for (const [shade, pct] of Object.entries(TINT_PERCENT)) {
      vars.push(`  --color-${c}-${shade}: color-mix(in oklab, ${value(c, 500)} ${pct}%, transparent);`);
    }
    const darkText = [`text-${c}-700`, `text-${c}-800`, `text-${c}-900`];
    rules.push(
      `  :where(.dark) .text-${c}-100 { color: ${value(c, 100)}; }`,
      `  :where(.dark) .text-${c}-200 { color: ${value(c, 200)}; }`,
      `  :where(.dark) .text-${c}-600 { color: ${value(c, 400)}; }`,
      `  :where(.dark) :is(${darkText.map((t) => `.${t}`).join(", ")}) { color: ${value(c, 300)}; }`,
      `  :where(.dark) .${esc(`hover:text-${c}-600`)}:hover { color: ${value(c, 400)}; }`,
      `  :where(.dark) :is(${darkText.map((t) => `.${esc(`hover:${t}`)}`).join(", ")}):hover { color: ${value(c, 300)}; }`,
    );
  }

  return `/* GENERATED by scripts/dark-palette.mjs from Tailwind's theme. Do not edit;
   run: node scripts/dark-palette.mjs > app/dark-palette.css

   Dark mode (app pages, .dark on <html>) for Tailwind's colour scales,
   ${PALETTE_COLORS[0]} to ${PALETTE_COLORS[PALETTE_COLORS.length - 1]}. Light mode is untouched.
   - Shades 50/100/200 become faint tints of the 500 colour, so pastel
     badges, banners, highlights and borders sit on dark cards instead of
     glowing (bg-, border-, ring-, from-… all follow, opacity variants too).
   - text-*-100/200 keep their light colour (light text on coloured fills).
   - text-*-600 reads as 400 and text-*-700/800/900 as 300 (hover: too), so
     coloured text stays readable on dark. Solid fills (bg-*-500…900, such
     as buttons with white text) keep their colours. */

.dark {
${vars.join("\n")}
}

@layer utilities {
${rules.join("\n")}
}
`;
}

export function readTailwindTheme(root = process.cwd()) {
  return fs.readFileSync(path.join(root, "node_modules", "tailwindcss", "theme.css"), "utf8");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.stdout.write(buildDarkPaletteCss(readTailwindTheme()));
}
